#!/usr/bin/env python3
"""Generate immutable builder-lane variants for taxonomy-balanced Online Search."""

from __future__ import annotations

import copy
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "config-manufacturing-anomaly.yaml"
LANES = (
    "control-native",
    "control-proxy-codx",
    "deepseek-codex",
    "deepseek-codex-dsml",
    "deepseek-claude",
    "deepseek-dsh",
    "deepseek-dsh-dsml",
)
DEEPSEEK_MODEL = "deepseek/deepseek-v4.1-flash"
CAMPAIGN = "online-search-taxonomy-balanced"


def variant(source: dict, lane: str) -> dict:
    config = copy.deepcopy(source)
    config["name"] = f"{CAMPAIGN}-{lane}"
    config["domain"] = "taxonomy-balanced-online-search"

    # BuildConfig.agent remains a schema-compatible placeholder. The explicit
    # benchmark.build_lane step below owns builder dispatch and never invokes
    # Yggdrasil's codx-backed build.codex implementation.
    config["build"]["agent"] = "codex"
    config["build"]["model"] = (
        "gpt-5.6-sol" if lane.startswith("control-") else DEEPSEEK_MODEL
    )
    config["build"]["reasoning_effort"] = "xhigh"
    config["build"]["fast_mode"] = False
    config["build"]["retry_budget"] = 0

    pipeline = []
    replaced = False
    for item in config["pipeline"]:
        step = item.get("step")
        if step in {"build.codex", "benchmark.build_lane"}:
            if replaced:
                raise ValueError("source config has multiple builder steps")
            pipeline.append(
                {
                    "step": "benchmark.build_lane",
                    "params": {
                        "lane": lane,
                        "instructions_file": item["params"]["instructions_file"],
                        "timeout_sec": item["params"].get("timeout_sec", 5400),
                    },
                }
            )
            replaced = True
        elif step not in {"deploy.gh_push", "deploy.open_pr"}:
            pipeline.append(item)
    if not replaced:
        raise ValueError("source config has no builder step")
    config["pipeline"] = pipeline
    config["traces"]["s3_prefix"] = (
        f"online-search/benchmark-traces/{config['name']}"
    )
    return config


def build_only_variant(source: dict, lane: str) -> dict:
    """Build and Oracle-check a package; skip NOP, solver, and deployment."""
    config = variant(source, lane)
    config["name"] = f"{CAMPAIGN}-build-only-{lane}"
    config["traces"]["s3_prefix"] = (
        f"online-search/benchmark-build-traces/{config['name']}"
    )
    excluded = {
        "oracle.score_nop",
        "difficulty.solver_lane",
        "doraemon.muse_solver_lane",
        "doraemon.publication_gate",
        "deploy.gh_push",
        "deploy.open_pr",
    }
    pipeline = []
    for item in config["pipeline"]:
        step = item.get("step")
        if step in excluded:
            continue
        pipeline.append(item)
    config["pipeline"] = pipeline
    return config


def main() -> None:
    source = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    for lane in LANES:
        full_output = ROOT / f"config-online-search-pipeline-{lane}.yaml"
        full_output.write_text(
            "# Generated by scripts/generate_online_search_benchmark_configs.py.\n"
            "# Taxonomy-balanced lane variant; deployment is intentionally disabled.\n"
            + yaml.safe_dump(
                variant(source, lane),
                sort_keys=False,
                allow_unicode=True,
                width=100,
            ),
            encoding="utf-8",
        )
        build_output = ROOT / f"config-online-search-build-only-{lane}.yaml"
        build_output.write_text(
            "# Generated by scripts/generate_online_search_benchmark_configs.py.\n"
            "# Build + Oracle phase: no NOP, solver, deployment, or PR stages.\n"
            + yaml.safe_dump(
                build_only_variant(source, lane),
                sort_keys=False,
                allow_unicode=True,
                width=100,
            ),
            encoding="utf-8",
        )
        print(full_output.name)
        print(build_output.name)


if __name__ == "__main__":
    main()
